/**
 * Animated Character Sprite System
 * Frame-based pixel art character with walk/jump/land animations
 */

import type { ColorPalette } from './palette'

// ============================================
// TYPES
// ============================================

export type CharacterAnimation = 'idle' | 'run' | 'jump' | 'fall' | 'land'

export type CharacterState = {
  animation: CharacterAnimation
  frameIndex: number
  frameTimer: number
  facingRight: boolean
}

export type CharacterColors = {
  hair: string
  skin: string
  shirt: string
  pants: string
  shoes: string
  outline: string
}

// ============================================
// ANIMATION CONFIG
// ============================================

type AnimationConfig = {
  frameCount: number
  frameDuration: number // ms per frame
  loop: boolean
  next?: CharacterAnimation
}

