/**
 * Gets the frame data for a given animation and frame index
 */
function getFrameData(animation: CharacterAnimation, frameIndex: number): FrameData {
  const frames: Record<CharacterAnimation, FrameData[]> = {
    idle: IDLE_FRAMES,
    run: RUN_FRAMES,
    jump: JUMP_FRAMES,
    fall: FALL_FRAMES,
    land: LAND_FRAMES,
  }

  const animFrames = frames[animation]
  return animFrames[frameIndex % animFrames.length]
}

/**
 * Creates initial character state
 */
export function createCharacterState(): CharacterState {
  return {
    animation: 'idle',
    frameIndex: 0,
    frameTimer: 0,
    facingRight: true,
  }
}

/**
 * Updates character animation state
 */
export function updateCharacterAnimation(
  state: CharacterState,
  deltaTime: number,
  newAnimation?: CharacterAnimation
): CharacterState {
  // Handle animation change
  if (newAnimation && newAnimation !== state.animation) {
    return {
      ...state,
      animation: newAnimation,
      frameIndex: 0,
      frameTimer: 0,
    }
  }

  const config = ANIMATIONS[state.animation]
  const newTimer = state.frameTimer + deltaTime

  if (newTimer >= config.frameDuration) {
    const nextFrame = state.frameIndex + 1

    // Handle animation end
    if (nextFrame >= config.frameCount) {
      if (config.loop) {
        return { ...state, frameIndex: 0, frameTimer: 0 }
      } else if (config.next) {
        return { ...state, animation: config.next, frameIndex: 0, frameTimer: 0 }
      }
      // Hold last frame
      return { ...state, frameTimer: 0 }
    }

    return { ...state, frameIndex: nextFrame, frameTimer: 0 }
  }

  return { ...state, frameTimer: newTimer }
}

/**
 * Determines animation from physics state
 */
export function getAnimationFromPhysics(
  grounded: boolean,
  wasGrounded: boolean,
  vy: number,
  vx: number,
  currentAnimation: CharacterAnimation
): CharacterAnimation {
  // Just landed
  if (grounded && !wasGrounded) {
    return 'land'
  }

  // In air
  if (!grounded) {
    if (vy < -1) return 'jump'
    if (vy > 1) return 'fall'
    return currentAnimation === 'jump' ? 'jump' : 'fall'
  }

  // Don't interrupt landing animation
  if (currentAnimation === 'land') {
    return 'land'
  }

  // On ground
  if (Math.abs(vx) > 0.5) {
    return 'run'
  }

  return 'idle'
}

/**
 * Renders the character to canvas
 */
export function renderCharacter(
  ctx: CanvasRenderingContext2D,
  x: number,
  y: number,
  state: CharacterState,
  palette: ColorPalette,
  scale: number = 1.5
): void {
  const frameData = getFrameData(state.animation, state.frameIndex)
  const colors = palette.character

  // Color map: 0=transparent, 1=outline, 2=hair, 3=skin, 4=shirt, 5=pants, 6=shoes
  const colorMap: Record<number, string> = {
    1: colors.outline,
    2: colors.hair,
    3: colors.skin,
    4: colors.shirt,
    5: colors.pants,
    6: colors.shoes,
  }

  ctx.save()

  // Handle facing direction
  if (!state.facingRight) {
    ctx.translate(x + 16 * scale, y)
    ctx.scale(-1, 1)
    x = 0
  } else {
    ctx.translate(x, y)
  }

  // Draw pixels
  for (let py = 0; py < frameData.length; py++) {
    for (let px = 0; px < frameData[py].length; px++) {
      const value = frameData[py][px]
      if (value === 0) continue

      ctx.fillStyle = colorMap[value] || colors.outline
      ctx.fillRect(Math.floor(px * scale), Math.floor(py * scale), Math.ceil(scale), Math.ceil(scale))
    }
  }

  ctx.restore()
}
